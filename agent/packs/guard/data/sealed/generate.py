def encoded(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


def timestamp(value):
    return value.astimezone(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z")


def parse_timestamp(value):
    return datetime.fromisoformat(value.replace("Z", "+00:00"))


def digest(value):
    return hashlib.sha256(value.encode("utf-8")).hexdigest()


def scenario_seed(family, repetition):
    return int(digest(f"{BASE_SEED}:{DESIGN_SEED}:{family}:{repetition}")[:16], 16) & ((1 << 63) - 1)


class Builder:
    def __init__(self, index, family, repetition):
        self.family = family
        self.repetition = repetition
        self.seed = scenario_seed(family, repetition)
        self.rng = random.Random(self.seed)
        self.token = digest(f"sealed:{self.seed}:{family}")[:18]
        self.user = PERSONA_FAMILY.get(family, USERS[(index + repetition) % len(USERS)])
        self.start = START + timedelta(days=index, hours=self.rng.randint(0, 4), minutes=self.rng.randint(0, 49))
        if self.user == "usr_priya":
            # Central Standard Time in November: 08:00-10:59 UTC is 2-4:59am.
            self.start = self.start.replace(hour=self.rng.randint(8, 10))
        elif self.user != "usr_marcus":
            self.start = self.start.replace(hour=self.rng.randint(15, 22))
        self.events = []
        self.call_id = f"call_sealed_{self.token}"
        self.new_device = f"h_sealed_device_{self.token}"
        self.home = HOME[self.user]
        self.remote = self.rng.choice(REGIONS)

    def event(self, kind, data, seconds, call=False):
        event = {
            "event_id": f"evt_sealed_{self.token}_{len(self.events) + 1:02d}",
            "user_id": self.user,
            "type": kind,
            "ts": timestamp(self.start + timedelta(seconds=seconds)),
            "source": "generator",
            "data": data,
        }
        if call:
            event["call_id"] = self.call_id
        self.events.append(event)
        return event

    def login(self, seconds, new=False, region=None, succeeded=True, alternate=0):
        device = f"{self.new_device}_{alternate}" if new and alternate else self.new_device if new else KNOWN[self.user]
        return self.event("login", {"device_hash": device, "region": region or self.home,
                                   "new_device": new, "succeeded": succeeded}, seconds)

    def call(self, seconds=0, verified=False, repeat=False, labeled=False, outbound=False):
        return self.event("call.started", {
            "direction": "out" if outbound else "in",
            "other_number_hash": f"h_sealed_caller_{self.token}",
            "attestation": "A" if verified else self.rng.choice(("B", "C", "none")),
            "seen_before": repeat, "scam_label": labeled,
        }, seconds, call=True)

